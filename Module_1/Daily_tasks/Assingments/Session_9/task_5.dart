void main() {
  // String is used because a name is made up of text.
  String name = "Sneh Horiya";

  // int is used because age is a whole number and does not contain decimals.
  int age = 20;

  // String is used because an email address is text.
  String email = "sneh@example.com";

  // double is used because height can include decimal values.
  double height = 5.8;

  // bool is used because it stores only true or false values.
  bool isStudent = true;

  print("Name: $name");
  print("Age: $age");
  print("Email: $email");
  print("Height: $height");
  print("Student: $isStudent");
}